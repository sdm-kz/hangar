// The icons a widget can name in its manifest (`icon`), by their lucide names. A fixed set rather than
// all of lucide: the whole set is either one bundle the size of the rest of the app or fifteen hundred
// lazy chunks, for a field most widgets fill with one of a dozen words. The guide lists these
// (server/Widgets/Guide/guide.md); anything else falls back to the generic one.
